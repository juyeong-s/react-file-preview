// Inlines the pdf.js worker as a string module so the PDF renderer works in
// every bundler without worker configuration. Runs before build/dev.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const workerPath = require.resolve('pdfjs-dist/build/pdf.worker.min.mjs');
const { version } = JSON.parse(readFileSync(join(dirname(workerPath), '..', 'package.json'), 'utf8'));
const code = readFileSync(workerPath, 'utf8');
const out = join(here, '..', 'src', 'renderers', 'pdf', 'worker-source.gen.js');
writeFileSync(
  out,
  `// Generated by scripts/gen-pdf-worker.mjs from pdfjs-dist@${version}. Do not edit.\nexport default ${JSON.stringify(code)};\n`,
);
console.log(`pdf worker inlined (pdfjs-dist@${version}, ${(code.length / 1024).toFixed(0)} KB)`);
